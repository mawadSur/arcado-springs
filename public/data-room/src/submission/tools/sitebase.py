        c.add('<g id="contours">')
        for lev, lines in sorted(LAYOUT['contours_2ft'].items(), key=lambda kv: int(kv[0])):
            idx = int(lev) % 10 == 0
            for ln in lines:
                c.pline([tuple(p) for p in ln], fill='none', stroke=(C['contour_txt'] if idx else C['contour']),
                        stroke_width=(0.9 if idx else 0.45), stroke_dasharray='7 3' if idx else '3 2')

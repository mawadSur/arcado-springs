def tag_ranges(tags, frontage=True):
    """'L1–L7 AND L19–L25' — the line-table tags of the courses on (or off) the Arcado Rd frontage."""
    nums = [int(t[1:]) for t, b in tags if bool(b['frontage']) == bool(frontage)]
    runs, start, prev = [], None, None
    for n in nums + [None]:
        if start is None:
            start = prev = n
            continue
        if n == prev + 1:
            prev = n
            continue
        runs.append((start, prev))
        start = prev = n
    return ' AND '.join('L%d' % a if a == b else 'L%d–L%d' % (a, b) for a, b in runs)



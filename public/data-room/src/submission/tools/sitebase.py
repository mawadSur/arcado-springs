def wrap(t, n=20):
    """greedy word wrap to n characters (same helper as tools/siteplan.py)."""
    words, lines, cur = str(t).split(), [], ''
    for w in words:
        if len(cur) + len(w) + 1 > n and cur:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur:
        lines.append(cur)
    return lines or ['']


# ============================================================================ geometry helpers
def dist(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def poly_area(p):
    return 0.5 * sum(p[i][0] * p[(i + 1) % len(p)][1] - p[(i + 1) % len(p)][0] * p[i][1] for i in range(len(p)))


def poly_centroid(p):
    A = poly_area(p)
    if abs(A) < 1e-9:
        return (sum(q[0] for q in p) / len(p), sum(q[1] for q in p) / len(p))
    cx = cy = 0.0
    for i in range(len(p)):
        x0, y0 = p[i]
        x1, y1 = p[(i + 1) % len(p)]
        f = x0 * y1 - x1 * y0
        cx += (x0 + x1) * f
        cy += (y0 + y1) * f
    return (cx / (6 * A), cy / (6 * A))


def point_in_poly(pt, poly):
    x, y = pt
    inside = False
    n = len(poly)
    for i in range(n):
        x0, y0 = poly[i]
        x1, y1 = poly[(i + 1) % n]
        if (y0 > y) != (y1 > y):
            if x0 + (y - y0) * (x1 - x0) / (y1 - y0) > x:
                inside = not inside
    return inside


def interp_v(path, u):
    """v on a polyline that is monotone in u (linear interpolation, clamped at the ends)."""
    if u <= path[0][0]:
        return path[0][1]
    for i in range(len(path) - 1):
        (u0, v0), (u1, v1) = path[i], path[i + 1]
        if u0 <= u <= u1 and u1 > u0:
            return v0 + (v1 - v0) * (u - u0) / (u1 - u0)
    return path[-1][1]


def rect(u0, u1, v0, v1):
    return [(u0, v0), (u1, v0), (u1, v1), (u0, v1)]


def offset_band(path, half):
    """A closed polygon 'half' feet either side of an open polyline (blunt ends)."""
    left, right = [], []
    n = len(path)
    for i, p in enumerate(path):
        a = path[max(i - 1, 0)]
        b = path[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / L, dx / L
        left.append((p[0] + nx * half, p[1] + ny * half))
        right.append((p[0] - nx * half, p[1] - ny * half))
    return left + right[::-1]



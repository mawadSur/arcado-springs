def finish(D):
    """Close the SVG (running the queued late layers) and append the disclaimer marker."""
    for fn in D.late:
        fn()
    D.add('</svg>')
    return D.render() + '\n<!-- %s -->\n<!-- %s -->\n' % (DISCLAIMER, MARKER)


def save(D, basename, dpi=150):
    """Write drawings/<basename>.svg and .png. Returns both paths."""
    svg_path = os.path.join(DRAW, basename + '.svg')
    png_path = os.path.join(DRAW, basename + '.png')
    os.makedirs(DRAW, exist_ok=True)
    with open(svg_path, 'w') as fh:
        fh.write(finish(D))
    fp.render_png(svg_path, png_path, dpi=dpi)
    return svg_path, png_path



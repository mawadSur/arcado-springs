class Drawing:
    """SVG collector. Plan methods take (u, v) feet; the s* methods take sheet points."""

    def __init__(self, s, x0, y0, fs=1.0, win=WIN):
        self.s, self.x0, self.y0, self.fs, self.win = s, x0, y0, fs, win
        self.out, self.late = [], []
        self.lab = Labeler()

    # -- transforms
    def X(self, u):
        return self.x0 + (u - self.win[0]) * self.s

    def Y(self, v):
        return self.y0 + (self.win[3] - v) * self.s

    def P(self, p):
        return '%.2f,%.2f' % (self.X(p[0]), self.Y(p[1]))

    def box(self):
        u0, u1, v0, v1 = self.win
        return (self.X(u0), self.Y(v1), (u1 - u0) * self.s, (v1 - v0) * self.s)

    # -- raw
    def add(self, t):
        self.out.append(t)

    def later(self, fn):
        self.late.append(fn)

    # -- plan-coordinate primitives
    def poly(self, pts, **kw):
        self.add('<polygon points="%s" %s/>' % (' '.join(self.P(p) for p in pts), attrs(kw)))

    def pline(self, pts, **kw):
        self.add('<polyline points="%s" %s/>' % (' '.join(self.P(p) for p in pts), attrs(kw)))

    def line(self, a, b, **kw):
        self.add('<line x1="%.2f" y1="%.2f" x2="%.2f" y2="%.2f" %s/>'
                 % (self.X(a[0]), self.Y(a[1]), self.X(b[0]), self.Y(b[1]), attrs(kw)))

    def circle(self, c, r_pt, **kw):
        self.add('<circle cx="%.2f" cy="%.2f" r="%.2f" %s/>' % (self.X(c[0]), self.Y(c[1]), r_pt, attrs(kw)))

    def tw(self, text, size):
        return 0.56 * size * self.fs * len(str(text))

    def text(self, u, v, t, size=6, anchor='middle', rot=0, bold=False, fill='#111', halo=False,
             avoid=False, dy=0):
        size = size * self.fs
        x, y = self.X(u), self.Y(v) + dy
        if avoid and rot == 0:
            y = self.lab.place(x, y, self.tw(t, size / self.fs), size, anchor)
        tr = ' transform="rotate(%.2f %.2f %.2f)"' % (rot, x, y) if rot else ''
        st = 'font-size="%.2f" text-anchor="%s" fill="%s"%s' % (size, anchor, fill, ' font-weight="bold"' if bold else '')
        if halo:
            self.add('<text x="%.2f" y="%.2f" %s stroke="#fff" stroke-width="%.2f" stroke-linejoin="round"%s>%s</text>'
                     % (x, y, st, size * 0.45, tr, esc(t)))
        self.add('<text x="%.2f" y="%.2f" %s%s>%s</text>' % (x, y, st, tr, esc(t)))

    def textlines(self, u, v, lines, size=6, anchor='middle', gap=1.15, avoid=False, bold_first=False,
                  fill='#111', halo=False):
        h = size * self.fs * gap
        x, y = self.X(u), self.Y(v)
        if avoid:
            w = max(self.tw(l, size) for l in lines)
            y = self.lab.place(x, y, w, h * len(lines), anchor)
        for i, l in enumerate(lines):
            st = ('font-size="%.2f" text-anchor="%s" fill="%s"%s'
                  % (size * self.fs, anchor, fill, ' font-weight="bold"' if (bold_first and i == 0) else ''))
            if halo:
                self.add('<text x="%.2f" y="%.2f" %s stroke="#fff" stroke-width="%.2f" stroke-linejoin="round">%s</text>'
                         % (x, y + i * h, st, size * self.fs * 0.45, esc(l)))
            self.add('<text x="%.2f" y="%.2f" %s>%s</text>' % (x, y + i * h, st, esc(l)))

    def rot_of(self, a, b):
        dx, dy = self.X(b[0]) - self.X(a[0]), self.Y(b[1]) - self.Y(a[1])
        ang = math.degrees(math.atan2(dy, dx))
        if ang > 90:
            ang -= 180
        if ang < -90:
            ang += 180
        return ang

    # -- sheet-point primitives
    def srect(self, x, y, w, h, **kw):
        self.add('<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" %s/>' % (x, y, w, h, attrs(kw)))

    def sline(self, x0, y0, x1, y1, **kw):
        self.add('<line x1="%.2f" y1="%.2f" x2="%.2f" y2="%.2f" %s/>' % (x0, y0, x1, y1, attrs(kw)))

    def spoly(self, pts, **kw):
        self.add('<polygon points="%s" %s/>' % (' '.join('%.2f,%.2f' % p for p in pts), attrs(kw)))

    def scircle(self, x, y, r, **kw):
        self.add('<circle cx="%.2f" cy="%.2f" r="%.2f" %s/>' % (x, y, r, attrs(kw)))

    def stext(self, x, y, t, size=7, anchor='start', bold=False, fill='#111', rot=0, italic=False):
        tr = ' transform="rotate(%.2f %.2f %.2f)"' % (rot, x, y) if rot else ''
        self.add('<text x="%.2f" y="%.2f" font-size="%.2f" text-anchor="%s" fill="%s"%s%s%s>%s</text>'
                 % (x, y, size, anchor, fill, ' font-weight="bold"' if bold else '',
                    ' font-style="italic"' if italic else '', tr, esc(t)))

    def stextblock(self, x, y, text, size=6.5, chars=120, lead=8.2, fill='#111', bold=False, indent=0.0):
        for j, ln in enumerate(wrap(text, chars)):
            self.stext(x + (0 if j == 0 else indent), y, ln, size=size, fill=fill, bold=bold)
            y += lead
        return y

    # -- clip helper
    def clip_open(self, poly=None, fill='#fff'):
        _CLIP[0] += 1
        cid = 'clip%d' % _CLIP[0]
        x, y, w, h = self.box()
        shape = ('<polygon points="%s"/>' % ' '.join(self.P(p) for p in poly)) if poly else \
                ('<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f"/>' % (x, y, w, h))
        self.add('<clipPath id="%s">%s</clipPath>' % (cid, shape))
        self.add('<g clip-path="url(#%s)" font-family=%s>' % (cid, '"' + FONT.replace("'", '') + '"'))
        if fill:
            self.add('<rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" fill="%s"/>' % (x, y, w, h, fill))
        return cid

    def clip_close(self):
        self.add('</g>')

    def render(self):
        return '\n'.join(self.out)


def table(D, x, y, cols, rows, size=6.5, rowh=None, widths=None, title=None, head_fill='#e8e8e8'):
    """Simple ruled table in sheet points (from siteplan.py); returns the bottom y."""
    rowh = rowh or size * 1.45
    widths = widths or [140] * len(cols)
    W = sum(widths)
    if title:
        D.stext(x, y, title, size=size + 2.5, bold=True)
        y += size + 4
    y_top = y
    D.srect(x, y, W, rowh, fill=head_fill, stroke='#000', stroke_width=0.6)
    cx = x
    for c, w in zip(cols, widths):
        D.stext(cx + 3, y + rowh * 0.72, c, size=size, bold=True)
        cx += w
    y += rowh
    for r in rows:
        nl = max(len(wrap(str(c), max(int(w / (0.56 * size)), 4))) for c, w in zip(r, widths))
        h = rowh * nl
        D.srect(x, y, W, h, fill='none', stroke='#000', stroke_width=0.4)
        cx = x
        for c, w in zip(r, widths):
            for i, ln in enumerate(wrap(str(c), max(int(w / (0.56 * size)), 4))):
                D.stext(cx + 3, y + rowh * 0.72 + i * rowh, ln, size=size)
            cx += w
        y += h
    cx = x
    for w in widths[:-1]:
        cx += w
        D.sline(cx, y_top, cx, y, stroke='#000', stroke_width=0.4)
    return y



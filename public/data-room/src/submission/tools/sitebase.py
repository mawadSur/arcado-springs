# --- WGS84 <-> local (u, v): least-squares affine fit to the 90 3DEP samples in
#     data/topo-samples.json, each of which carries u, v, lon and lat. Residual is
#     reported by the self-check (it is under 0.01 ft), so lon/lat source geometry —
#     e.g. public building footprints — can be brought into the drawing without any
#     hand-transcribed local coordinates.
def _fit_affine():
    S = TOPO['samples']
    rows = [[s['u'], s['v'], 1.0] for s in S]

    def solve(ys):
        A = [[0.0] * 3 for _ in range(3)]
        B = [0.0] * 3
        for r, y in zip(rows, ys):
            for i in range(3):
                B[i] += r[i] * y
                for j in range(3):
                    A[i][j] += r[i] * r[j]
        M = [A[i] + [B[i]] for i in range(3)]
        for i in range(3):
            p = max(range(i, 3), key=lambda k: abs(M[k][i]))
            M[i], M[p] = M[p], M[i]
            for k in range(3):
                if k != i:
                    f = M[k][i] / M[i][i]
                    for j in range(i, 4):
                        M[k][j] -= f * M[i][j]
        return [M[i][3] / M[i][i] for i in range(3)]

    return solve([s['lon'] for s in S]), solve([s['lat'] for s in S])


_LON, _LAT = _fit_affine()
_DET = _LON[0] * _LAT[1] - _LON[1] * _LAT[0]


def uv_of(lon, lat):
    """WGS84 degrees -> site-local (u, v) feet."""
    dx, dy = lon - _LON[2], lat - _LAT[2]
    return ((_LAT[1] * dx - _LON[1] * dy) / _DET, (-_LAT[0] * dx + _LON[0] * dy) / _DET)


def lonlat_of(u, v):
    return (_LON[0] * u + _LON[1] * v + _LON[2], _LAT[0] * u + _LAT[1] * v + _LAT[2])


def affine_residual_ft():
    """Max |fit - source| over the 90 samples, in feet (1 deg latitude ~ 364,000 ft)."""
    worst = 0.0
    for s in TOPO['samples']:
        lo, la = lonlat_of(s['u'], s['v'])
        worst = max(worst, abs(lo - s['lon']) * 303000.0, abs(la - s['lat']) * 364000.0)
    return worst



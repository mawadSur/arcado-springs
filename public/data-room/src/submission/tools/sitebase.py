def north_arrow(c, x, y, r=30.0):
    """Grid-north arrow at sheet point (x, y). North is NORTH_DEG above the +u axis, and
    +v is up on the drawing, so on paper north points up and to the right."""
    a = math.radians(NORTH_DEG)
    dx, dy = math.cos(a), -math.sin(a)
    px, py = -dy, dx
    c.scircle(x, y, r, fill='#fff', stroke='#000', stroke_width=0.8)
    tip = (x + dx * r * 0.86, y + dy * r * 0.86)
    tail = (x - dx * r * 0.78, y - dy * r * 0.78)
    c.sline(tail[0], tail[1], tip[0], tip[1], stroke='#000', stroke_width=2.0)
    c.spoly([tip, (tip[0] - 17 * dx + 6.0 * px, tip[1] - 17 * dy + 6.0 * py),
             (tip[0] - 17 * dx - 6.0 * px, tip[1] - 17 * dy - 6.0 * py)], fill='#000')
    c.stext(tip[0] + 11 * dx, tip[1] + 11 * dy + 4, 'N', size=13, bold=True, anchor='middle')
    c.stext(x, y + r + 11, 'GRID NORTH (SR 2240 GA WEST)', size=6, anchor='middle')
    c.stext(x, y + r + 19, '= 28°43\' ABOVE THE +u AXIS', size=6, anchor='middle')


def scalebar(c, x, y, scale=SCALE60, step_ft=60, steps=4):
    """Graphic scale bar at sheet point (x, y) = left end of the bar."""
    h = 7.0
    for k in range(steps):
        c.srect(x + step_ft * scale * k, y, step_ft * scale, h,
                fill='#000' if k % 2 == 0 else '#fff', stroke='#000', stroke_width=0.6)
        c.stext(x + step_ft * scale * k, y - 4, str(step_ft * k), size=6.5, anchor='middle')
    c.stext(x + step_ft * scale * steps, y - 4, '%d ft' % (step_ft * steps), size=6.5, anchor='middle')
    c.stext(x + step_ft * scale * steps / 2.0, y + h + 11,
            'GRAPHIC SCALE  1" = %d\'' % round(72.0 / scale), size=8, bold=True, anchor='middle')



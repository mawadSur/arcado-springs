class Labeler:
    """Greedy label-collision avoidance in sheet points; nudges along y (from siteplan.py)."""

    def __init__(self):
        self.boxes = []

    def hit(self, b):
        return any(not (b[2] < o[0] or b[0] > o[2] or b[3] < o[1] or b[1] > o[3]) for o in self.boxes)

    def place(self, x, y, w, h, anchor='middle'):
        for k in range(0, 9):
            for sgn in (1, -1) if k else (1,):
                yy = y + sgn * k * (h + 1.5)
                x0 = x - w / 2 if anchor == 'middle' else (x if anchor == 'start' else x - w)
                b = (x0, yy - h * 0.8, x0 + w, yy + h * 0.3)
                if not self.hit(b):
                    self.boxes.append(b)
                    return yy
        self.boxes.append((x - w / 2, y - h, x + w / 2, y))
        return y

    def reserve(self, x0, y0, x1, y1):
        self.boxes.append((x0, y0, x1, y1))


